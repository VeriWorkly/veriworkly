import { ENGINE_VERSION } from "@veriworkly/ats-engine";
import { describe, expect, it } from "vitest";

import { reportToPlainText } from "@/features/ats-checker/services";
import { scoreTone, sortByCategoryOrder } from "@/features/ats-checker/data";
import type { AtsFullReport } from "@/features/ats-checker/types";

function report(overrides: Partial<AtsFullReport> = {}): AtsFullReport {
  return {
    version: "ats-v2",
    restricted: false,
    verdict: "needs-work",
    readinessScore: 74,
    jobMatchScore: 61,

    parsed: {
      name: "Jane Doe",
      email: "jane@example.com",
      phone: "",
      links: [],
      roles: [],
      education: [],
      skills: [],
      certifications: [],
      spokenLanguages: [],
      monthsOfExperience: null,
      highestIsced: null,
      provenance: {
        name: "parser",
        email: "parser",
        phone: "none",
        roles: "none",
        education: "none",
        skills: "none",
        certifications: "none",
        spokenLanguages: "none",
      },
    },

    matchedKeywords: ["react", "typescript"],
    missingKeywords: ["kubernetes"],
    matchedKeywordGroups: { hard: ["react", "typescript"], soft: [] },
    missingKeywordGroups: { hard: ["kubernetes"], soft: [] },
    advice: [],
    parsingWarnings: [],
    strengths: ["Contact details sit in the top 30%"],

    // Run order, smaller fix first: the copied report has to sort them itself.
    failedChecks: [
      {
        id: "ats-v2.structure.skills",
        category: "structure",
        severity: "error",
        passed: false,
        evidence: "No skills section found",
        scoreImpact: 6,
        fix: "Add a labelled Skills section.",
      },
      {
        id: "ats-v2.content.metrics",
        category: "content",
        severity: "warning",
        passed: false,
        evidence: "2 of 14 bullets carry a number",
        scoreImpact: 10,
        fix: "Quantify more bullets.",
      },
    ],

    prioritizedFixes: ["Add a labelled Skills section.", "Quantify more bullets."],

    rules: [],

    categories: [
      { category: "content", score: 48, passed: 1, total: 3, lost: 10, possible: 20 },
      { category: "parse", score: 100, passed: 2, total: 2, lost: 0, possible: 20 },
    ],

    checksPassed: 9,
    checksTotal: 11,
    wordCount: 612,
    locale: { languages: [], region: null, unsupported: null },
    engine: { version: ENGINE_VERSION, policy: "ats-v2+00000000" },
    requirements: [],
    ...overrides,
  };
}

describe("ATS report as clipboard text", () => {
  it("orders fixes by points recovered, not by the order the rules ran", () => {
    const text = reportToPlainText(report(), "https://veriworkly.com");

    expect(text).toContain("1. Quantify more bullets.");
    expect(text).toContain("2. Add a labelled Skills section.");
    expect(text.indexOf("Quantify more bullets.")).toBeLessThan(
      text.indexOf("Add a labelled Skills section."),
    );
  });

  it("carries the evidence and the points beside each fix", () => {
    const text = reportToPlainText(report(), "https://veriworkly.com");

    expect(text).toContain("Why: 2 of 14 bullets carry a number");
    expect(text).toContain("Worth: 10 points");
  });

  it("labels an unscored job match instead of printing null", () => {
    const text = reportToPlainText(report({ jobMatchScore: null }), "https://veriworkly.com");

    expect(text).toContain("Job match: not scored (no job description provided)");
    expect(text).not.toContain("null");
    // With no job description there are no keyword lists to report either.
    expect(text).not.toContain("KEYWORDS");
  });

  it("says 'none' rather than leaving an empty keyword line dangling", () => {
    const text = reportToPlainText(
      report({
        matchedKeywords: [],
        missingKeywords: [],
        matchedKeywordGroups: { hard: [], soft: [] },
        missingKeywordGroups: { hard: [], soft: [] },
      }),
      "https://veriworkly.com",
    );

    expect(text).toContain("Matched: none");
    expect(text).toContain("Missing: none");
  });

  it("omits sections that have nothing in them", () => {
    const text = reportToPlainText(
      report({ failedChecks: [], strengths: [] }),
      "https://veriworkly.com",
    );

    expect(text).not.toContain("FIX THESE FIRST");
    expect(text).not.toContain("ALREADY WORKING");
  });

  it("attributes the report to the checker URL", () => {
    expect(reportToPlainText(report(), "https://veriworkly.com")).toContain(
      "Generated by https://veriworkly.com/ats-checker",
    );
  });
});

describe("ATS category presentation helpers", () => {
  it("presents areas in pipeline order regardless of the order the engine sent them", () => {
    const ordered = sortByCategoryOrder([
      { category: "format" },
      { category: "contact" },
      { category: "parse" },
    ]);

    expect(ordered.map((entry) => entry.category)).toEqual(["parse", "contact", "format"]);
  });

  it("puts an unrecognised category last instead of dropping it", () => {
    const ordered = sortByCategoryOrder([{ category: "brand-new" }, { category: "parse" }]);

    expect(ordered.map((entry) => entry.category)).toEqual(["parse", "brand-new"]);
  });

  it("bands scores on the same thresholds the gauge and the bars share", () => {
    // The engine's verdict bands, so a "good" tone is always a "strong" verdict.
    expect(scoreTone(75)).toBe("good");
    expect(scoreTone(74)).toBe("warn");
    expect(scoreTone(45)).toBe("warn");
    expect(scoreTone(44)).toBe("bad");
  });
});

describe("the rest of the report in the copied text", () => {
  it("carries the parsing warnings, each requirement and what the ATS recovered", () => {
    const text = reportToPlainText(
      report({
        parsingWarnings: ["The resume reads as two columns."],
        requirements: [
          {
            text: "5+ years of TypeScript",
            status: "missing",
            importance: "required",
            kind: "experience",
            terms: [{ term: "typescript", found: false }],
            evidence: [],
            detail: "3 years shown",
          },
          {
            text: "React",
            status: "met",
            importance: "required",
            kind: "skills",
            terms: [{ term: "react", found: true }],
            evidence: ["Built the React checkout"],
            detail: null,
          },
        ] as AtsFullReport["requirements"],
      }),
      "https://veriworkly.com",
    );

    expect(text).toContain("PARSING WARNINGS");
    expect(text).toContain("! The resume reads as two columns.");
    expect(text).toContain("[Not shown] 5+ years of TypeScript");
    expect(text).toContain("   3 years shown");
    expect(text).toContain("   Evidence: Built the React checkout");
    expect(text.indexOf("[Not shown]")).toBeLessThan(text.indexOf("[Met]"));
    expect(text).toContain("WHAT THE ATS SEES");
    expect(text).toContain("Name: Jane Doe");
    expect(text).toContain("Phone: not found");
    expect(text).toContain("Work history (0 rows):");
  });

  it("lists soft skills apart and the advice, marked as not scored", () => {
    const text = reportToPlainText(
      report({
        jobMatchScore: 60,
        missingKeywords: ["kubernetes", "communication"],
        missingKeywordGroups: { hard: ["kubernetes"], soft: ["communication"] },
        advice: [
          {
            id: "file.name",
            kind: "file",
            message: "The file name does not say whose resume it is.",
            fix: "Name it Jane-Doe-Resume.pdf.",
          },
        ],
      }),
      "https://www.veriworkly.com",
    );
    expect(text).toContain("Missing: kubernetes");
    expect(text).toContain("Soft skills mentioned (weigh less): communication");
    expect(text).toContain("WORTH KNOWING (NOT SCORED)");
    expect(text).toContain("* The file name does not say whose resume it is.");
  });
});
