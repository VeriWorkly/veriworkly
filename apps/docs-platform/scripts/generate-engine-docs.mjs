/**
 * Builds the generated pages of the ATS Engine docs from the installed `@veriworkly/ats-engine`:
 *
 *   - `reference/rubric.md`    from `policyRubric(DEFAULT_POLICY)`: every rule, weight and fix
 *   - `reference/locales.md`   from `BUILT_IN_LOCALES`: the language and region packs
 *   - `reference/*.mdx`        type tables read from the package's `.d.ts` files and their JSDoc
 *   - `project/changelog.md`   the package's own CHANGELOG.md
 *
 * Runs before `dev` and `build` (see `predev` / `prebuild`), so these pages always describe the
 * engine version this app has installed, the same one the server, site and studio run. Edit the
 * engine (or the intros below), never the generated files: they are overwritten here.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

import ts from "typescript";
import * as prettier from "prettier";
import { CATEGORY_LABELS, CATEGORY_ORDER } from "@veriworkly/ats-engine/format";
import { BUILT_IN_LOCALES } from "@veriworkly/ats-engine/locales";
import {
  DEFAULT_POLICY,
  ENGINE_VERSION,
  policyRubric,
  policyFingerprint,
} from "@veriworkly/ats-engine";

const appRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDir = path.join(appRoot, "content/ats-engine");

const require = createRequire(import.meta.url);
const enginePackageJson = require.resolve("@veriworkly/ats-engine/package.json");
const engineRoot = path.dirname(enginePackageJson);
const engineDist = path.join(engineRoot, "dist");

const repoUrl = "https://github.com/VeriWorkly/ats-engine";
const generatedNote = `{/* Generated by scripts/generate-engine-docs.mjs from @veriworkly/ats-engine ${ENGINE_VERSION}. Do not edit. */}`;
const generatedNoteMd = `<!-- Generated by scripts/generate-engine-docs.mjs from @veriworkly/ats-engine ${ENGINE_VERSION}. Do not edit. -->`;

/* ------------------------------------------------------------------ helpers */

const prettierConfig = await prettier.resolveConfig(path.join(outputDir, "index.mdx"));

async function write(relativePath, content) {
  const filePath = path.join(outputDir, relativePath);
  const parser = filePath.endsWith(".mdx") ? "mdx" : "markdown";
  const formatted = await prettier.format(content, { ...prettierConfig, plugins: [], parser });

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, formatted);
}

/** `metaTitle` replaces `title` in `<title>` when another page already uses the same title. */
function frontmatter(title, description, metaTitle) {
  const meta = metaTitle ? `metaTitle: ${JSON.stringify(metaTitle)}\n` : "";

  return `---\ntitle: ${JSON.stringify(title)}\n${meta}description: ${JSON.stringify(description)}\n---\n`;
}

/** A Markdown table cell: one line, with its pipes escaped. */
function cell(text) {
  return String(text).replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
}

/* ------------------------------------------------------------------ rubric */

async function writeRubric() {
  const rubric = policyRubric(DEFAULT_POLICY);
  const fingerprint = policyFingerprint(DEFAULT_POLICY);

  const sections = CATEGORY_ORDER.map((category) => {
    const rules = rubric.filter((rule) => rule.category === category);
    if (rules.length === 0) return "";

    const isDeduction = rules.every((rule) => rule.deduction);
    const total = rules.reduce((sum, rule) => sum + rule.points, 0);
    const summary = isDeduction
      ? `${rules.length} rules, up to ${total} points deducted in all.`
      : `${rules.length} rules, ${total} points of weight.`;

    const rows = rules.map((rule) => {
      const weight = rule.deduction ? `−${rule.points} pts` : String(rule.points);

      return `| \`${rule.id}\` | ${rule.severity} | ${cell(rule.measures)} | ${weight} | ${cell(rule.passes)} | ${cell(rule.fix)} |`;
    });

    return [
      `## ${CATEGORY_LABELS[category] ?? category}`,
      "",
      summary,
      "",
      "| Rule | Severity | Reads | Weight | Passes when | Fix |",
      "| --- | --- | --- | --- | --- | --- |",
      ...rows,
    ].join("\n");
  });

  const unknown = rubric.filter((rule) => !CATEGORY_ORDER.includes(rule.category));
  if (unknown.length > 0) {
    throw new Error(`Rubric categories missing from CATEGORY_ORDER: ${unknown.map((r) => r.id)}`);
  }

  const body = `${frontmatter(
    "Scoring rubric",
    `Every rule the community policy scores, with its weight, what it reads, when it passes and the fix. Engine ${ENGINE_VERSION}.`,
  )}
${generatedNoteMd}

Engine **${ENGINE_VERSION}**, policy \`${fingerprint}\`, ${rubric.length} rules. This page is built from
\`policyRubric(DEFAULT_POLICY)\` when the docs are built, so it always matches the installed engine.
Call \`policyRubric(policy)\` yourself to get the same table for a policy of your own.

- **Score.** Each rule that applies can lose its weight. The readiness score is the share of the
  applicable weight kept, 0–100. A rule whose evidence is absent (page geometry for pasted text, a
  posting for the copied-posting check) is left out of both the report and the score.
- **Deductions.** Integrity rules (\`−n pts\`) come off the finished score in points and are never part
  of the weighing: an honest resume scores exactly as if they did not exist.
- **Determinism.** The same input, reference date (\`now\`), engine version and policy fingerprint
  always give the same report. Every report carries \`engine.version\` and \`engine.policy\`.
- **Writing rules** read English only. For a resume in another language they drop out instead of
  judging it on English words.

See [Scoring and the rubric](/ats-engine/concepts/scoring) for how the score is put together.

${sections.filter(Boolean).join("\n\n")}
`;

  await write("reference/rubric.md", body);
  return rubric.length;
}

/* ------------------------------------------------------------------ locales */

async function writeLocales() {
  const { languages, regions } = BUILT_IN_LOCALES;

  const languageRows = languages.map(
    (pack) =>
      `| \`${pack.id}\` | ${cell(pack.name)} | ${pack.status} | ${pack.script ? cell(pack.script) : "Latin"} | ${pack.defaultRegion ?? "–"} |`,
  );

  const regionRows = regions.map((pack) => {
    const order = { MDY: "month first", DMY: "day first", YMD: "year first" }[pack.dateOrder];

    return `| \`${pack.id}\` | ${cell(pack.name)} | ${pack.status} | +${cell(pack.phoneCountry)} | ${order ?? pack.dateOrder} |`;
  });

  const body = `${frontmatter(
    "Languages and regions",
    `The language and region packs built into engine ${ENGINE_VERSION}, and their review status.`,
    "Language and region packs reference",
  )}
${generatedNoteMd}

The packs exported from \`@veriworkly/ats-engine/locales\` as \`BUILT_IN_LOCALES\` in engine
**${ENGINE_VERSION}**. English is the policy's base vocabulary, not a pack. Attach packs with
\`withLocales\`; see [Languages and regions](/ats-engine/guides/languages-and-regions).

A pack is \`verified\` only once a named native-speaking maintainer has reviewed it; until then it is
\`community\`.

## Language packs

| Id | Name | Status | Script | Default region |
| --- | --- | --- | --- | --- |
${languageRows.join("\n")}

## Region packs

A region sets how all-numeric dates are read, which national credentials are recognised, and how
rules such as a stated date of birth or a photo are weighed.

| Id | Name | Status | Phone country | Numeric dates |
| --- | --- | --- | --- | --- |
${regionRows.join("\n")}
`;

  await write("reference/locales.md", body);
}

/* ------------------------------------------------------------------ changelog */

async function writeChangelog() {
  const changelog = fs.readFileSync(path.join(engineRoot, "CHANGELOG.md"), "utf8");

  // Drop the package-name heading and the note about changesets: start at the first release.
  const firstRelease = changelog.search(/^## /m);
  const releases = firstRelease === -1 ? changelog : changelog.slice(firstRelease);

  const body = `${frontmatter(
    "Changelog",
    "What changed in each release of @veriworkly/ats-engine, with breaking changes marked.",
  )}
${generatedNoteMd}

Copied from the package's [CHANGELOG.md](${repoUrl}/blob/main/CHANGELOG.md) when the docs are built.
While the engine is 0.x, any change to a score or to the report's shape is a minor release marked
**Breaking:**. Releases of the MCP server are listed in
[its own changelog](${repoUrl}/blob/main/packages/mcp/CHANGELOG.md).

${releases}
`;

  await write("project/changelog.md", body);
}

/* ------------------------------------------------------------------ type tables */

const typeFiles = {
  types: path.join(engineDist, "types.d.ts"),
  parsed: path.join(engineDist, "types/parsed.d.ts"),
  engine: path.join(engineDist, "scoring/engine.d.ts"),
  ai: path.join(engineDist, "ai/index.d.ts"),
  aiRun: path.join(engineDist, "ai/run.d.ts"),
};

const program = ts.createProgram(Object.values(typeFiles), {
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  target: ts.ScriptTarget.ES2022,
  strict: true,
  exactOptionalPropertyTypes: true,
});
const checker = program.getTypeChecker();

/** JSX for MDX: text as string literals, `code` spans as <code>, so no character needs escaping. */
function toJsx(text) {
  if (!text) return '""';

  const parts = text
    .replace(/\s*\n\s*/g, " ")
    .split(/(`[^`]+`)/)
    .filter(Boolean)
    .map((part) =>
      part.startsWith("`")
        ? `<code>{${JSON.stringify(part.slice(1, -1))}}</code>`
        : `{${JSON.stringify(part)}}`,
    );

  return `<>${parts.join("")}</>`;
}

function typeTable(fileKey, typeName) {
  const sourceFile = program.getSourceFile(typeFiles[fileKey]);
  if (!sourceFile) throw new Error(`No source file for ${fileKey}`);

  const declaration = sourceFile.statements.find(
    (statement) => ts.isTypeAliasDeclaration(statement) && statement.name.text === typeName,
  );
  if (!declaration) throw new Error(`${typeName} is not declared in ${typeFiles[fileKey]}`);

  const type = checker.getTypeAtLocation(declaration.name);
  const entries = checker.getPropertiesOfType(type).map((property) => {
    const propertyDeclaration = property.declarations?.[0];
    const rawType =
      propertyDeclaration && "type" in propertyDeclaration && propertyDeclaration.type
        ? propertyDeclaration.type.getText()
        : checker.typeToString(checker.getTypeOfSymbol(property));
    const fullType = rawType
      .replace(/\s+/g, " ")
      .replace(/ \| undefined$/, "")
      .trim();
    const shortType = fullType.length > 48 ? (fullType.startsWith("{") ? "object" : "…") : fullType;
    const description = ts.displayPartsToString(property.getDocumentationComment(checker));
    const deprecated = property.getJsDocTags(checker).some((tag) => tag.name === "deprecated");
    const required = (property.flags & ts.SymbolFlags.Optional) === 0;

    const fields = [
      `type: ${JSON.stringify(shortType)}`,
      shortType !== fullType ? `typeDescription: ${JSON.stringify(fullType)}` : null,
      description ? `description: ${toJsx(description)}` : null,
      required ? "required: true" : null,
      deprecated ? "deprecated: true" : null,
    ].filter(Boolean);

    return `    ${JSON.stringify(property.name)}: { ${fields.join(", ")} },`;
  });

  const docs = ts.displayPartsToString(
    checker.getSymbolAtLocation(declaration.name)?.getDocumentationComment(checker) ?? [],
  );

  return [
    `## \`${typeName}\``,
    "",
    docs ? docs.replace(/\s*\n\s*/g, " ").replace(/[{}<>]/g, (c) => `\\${c}`) : "",
    "",
    `<TypeTable\n  type={{\n${entries.join("\n")}\n  }}\n/>`,
  ].join("\n");
}

async function writeTypePage(file, title, description, intro, tables) {
  const body = `${frontmatter(title, description)}
${generatedNote}

${intro}

${tables.map(([fileKey, typeName]) => typeTable(fileKey, typeName)).join("\n\n")}
`;

  await write(file, body);
}

async function writeTypePages() {
  await writeTypePage(
    "reference/check-options.mdx",
    "check() options",
    "Everything check() reads besides the resume and the policy.",
    `\`check(resume, policy = DEFAULT_POLICY, options)\` returns an [\`AtsReport\`](/ats-engine/reference/report).
The table is read from the engine's own type declarations (engine ${ENGINE_VERSION}). Every option is
optional, and each accepts \`undefined\` as absent.`,
    [
      ["engine", "AtsCheckOptions"],
      ["types", "AtsFileInfo"],
    ],
  );

  await writeTypePage(
    "reference/report.mdx",
    "The report",
    "Every field of AtsReport and the parsed record, read from the engine's type declarations.",
    `What \`check()\` returns. The report is a pure function of the resume, the policy and the options
(\`now\` included). Read from the engine's own type declarations (engine ${ENGINE_VERSION}).`,
    [
      ["types", "AtsReport"],
      ["types", "AtsRuleResult"],
      ["types", "AtsCategoryScore"],
      ["types", "AtsRequirement"],
      ["types", "AtsKeywordGroups"],
      ["types", "AtsAdvice"],
      ["parsed", "AtsParsedResume"],
      ["parsed", "AtsParsedRole"],
      ["parsed", "AtsParsedEducation"],
      ["parsed", "AtsParsedCertification"],
      ["parsed", "AtsParsedLanguage"],
      ["parsed", "AtsParsedDate"],
    ],
  );

  await writeTypePage(
    "reference/ai-options.mdx",
    "AI options",
    "The options of createAtsAi, a task's route, and what every AI call returns.",
    `From \`@veriworkly/ats-engine/ai\`. Read from the engine's own type declarations (engine
${ENGINE_VERSION}). See [AI features](/ats-engine/guides/ai) for how to use them.`,
    [
      ["ai", "AtsAiOptions"],
      ["aiRun", "TaskRoute"],
      ["aiRun", "AtsAiResult"],
    ],
  );
}

/* ------------------------------------------------------------------ run */

const ruleCount = await writeRubric();
await writeLocales();
await writeChangelog();
await writeTypePages();

console.log(
  `Generated the ATS Engine reference for engine ${ENGINE_VERSION}: ${ruleCount} rules, locales, changelog, type tables.`,
);
